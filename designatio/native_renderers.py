from __future__ import annotations

from pathlib import Path
from typing import Any, Callable


def _safe_text(value: Any) -> str:
    return str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def _components(project: dict[str, Any]) -> list[dict[str, Any]]:
    return project.get("components") or [
        {"type": "header", "title": project["name"], "description": "Production-ready interface"},
        {"type": "card", "title": "Primary overview", "description": "Start with real content."},
        {"type": "card", "title": "Supporting details", "description": "Accessible responsive details."},
    ]


def render_flutter(project: dict[str, Any], output_dir: str | Path) -> dict[str, Any]:
    output = Path(output_dir)
    lib = output / "lib"
    lib.mkdir(parents=True, exist_ok=True)
    components = _components(project)
    header = next((item for item in components if item.get("type") == "header"), components[0])
    cards = [item for item in components if item.get("type") != "header"]
    card_widgets = "\n".join(
        '            Card(child: Padding(padding: const EdgeInsets.all(16), child: '
        'Column(crossAxisAlignment: CrossAxisAlignment.start, children: ['
        f'Text("{_safe_text(card.get("title", "Card"))}", style: Theme.of(context).textTheme.titleMedium),'
        'const SizedBox(height: 8),'
        f'Text("{_safe_text(card.get("description", ""))}")'
        '])))'
        for card in cards
    )
    source = f'''import 'package:flutter/material.dart';

void main() => runApp(const DesignatioApp());

class DesignatioApp extends StatelessWidget {{
  const DesignatioApp({{super.key}});

  @override
  Widget build(BuildContext context) {{
    return MaterialApp(
      title: '{_safe_text(project["name"])}',
      theme: ThemeData(
        useMaterial3: true,
        colorScheme: ColorScheme.fromSeed(seedColor: const Color(0xFF4F46E5)),
      ),
      home: const DesignatioScreen(),
    );
  }}
}}

class DesignatioScreen extends StatelessWidget {{
  const DesignatioScreen({{super.key}});

  @override
  Widget build(BuildContext context) {{
    return Scaffold(
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(24),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text("{_safe_text(header.get("title", project["name"]))}",
                  style: Theme.of(context).textTheme.headlineMedium),
              const SizedBox(height: 8),
              Text("{_safe_text(header.get("description", ""))}",
                  style: Theme.of(context).textTheme.bodyLarge),
              const SizedBox(height: 24),
{card_widgets},
            ],
          ),
        ),
      ),
    );
  }}
}}
'''
    (lib / "main.dart").write_text(source, encoding="utf-8")
    (output / "pubspec.yaml").write_text(
        f'name: designatio_generated\ndescription: Generated by Designatio\npublish_to: "none"\n'
        'environment:\n  sdk: ">=3.0.0 <4.0.0"\n'
        'dependencies:\n  flutter:\n    sdk: flutter\n'
        '  cupertino_icons: ^1.0.8\n',
        encoding="utf-8",
    )
    return {"renderer": "flutter", "entry": str((lib / "main.dart").resolve()), "files": [str((lib / "main.dart").resolve())]}


def render_swiftui(project: dict[str, Any], output_dir: str | Path) -> dict[str, Any]:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    components = _components(project)
    header = next((item for item in components if item.get("type") == "header"), components[0])
    cards = [item for item in components if item.get("type") != "header"]
    card_views = "\n".join(
        '                VStack(alignment: .leading, spacing: 8) {\n'
        f'                    Text("{_safe_text(card.get("title", "Card"))}")\n'
        '                        .font(.headline)\n'
        f'                    Text("{_safe_text(card.get("description", ""))}")\n'
        '                        .foregroundStyle(.secondary)\n'
        '                }\n'
        '                .padding()\n'
        '                .frame(maxWidth: .infinity, alignment: .leading)\n'
        '                .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 12))'
        for card in cards
    )
    source = f'''import SwiftUI

struct ContentView: View {{
    var body: some View {{
        ScrollView {{
            VStack(alignment: .leading, spacing: 24) {{
                VStack(alignment: .leading, spacing: 8) {{
                    Text("{_safe_text(header.get("title", project["name"]))}")
                        .font(.largeTitle.weight(.bold))
                    Text("{_safe_text(header.get("description", ""))}")
                        .foregroundStyle(.secondary)
                }}

{card_views}
            }}
            .padding()
        }}
    }}
}}

#Preview {{
    ContentView()
}}
'''
    (output / "ContentView.swift").write_text(source, encoding="utf-8")
    return {"renderer": "swiftui", "entry": str((output / "ContentView.swift").resolve()), "files": [str((output / "ContentView.swift").resolve())]}


def render_compose(project: dict[str, Any], output_dir: str | Path) -> dict[str, Any]:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    components = _components(project)
    header = next((item for item in components if item.get("type") == "header"), components[0])
    cards = [item for item in components if item.get("type") != "header"]
    card_views = "\n".join(
        '        Card(modifier = Modifier.fillMaxWidth()) {\n'
        '            Column(modifier = Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {\n'
        f'                Text("{_safe_text(card.get("title", "Card"))}", style = MaterialTheme.typography.titleMedium)\n'
        f'                Text("{_safe_text(card.get("description", ""))}", style = MaterialTheme.typography.bodyMedium)\n'
        '            }\n'
        '        }'
        for card in cards
    )
    source = f'''package com.designatio.generated

import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp

@Composable
fun DesignatioScreen() {{
    Column(
        modifier = Modifier.fillMaxSize().padding(24.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {{
        Text("{_safe_text(header.get("title", project["name"]))}", style = MaterialTheme.typography.headlineMedium)
        Text("{_safe_text(header.get("description", ""))}", style = MaterialTheme.typography.bodyLarge)
{card_views}
    }}
}}
'''
    (output / "DesignatioScreen.kt").write_text(source, encoding="utf-8")
    return {"renderer": "compose", "entry": str((output / "DesignatioScreen.kt").resolve()), "files": [str((output / "DesignatioScreen.kt").resolve())]}


def render_egui(project: dict[str, Any], output_dir: str | Path) -> dict[str, Any]:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    components = _components(project)
    header = next((item for item in components if item.get("type") == "header"), components[0])
    cards = [item for item in components if item.get("type") != "header"]
    card_views = "\n".join(
        '        ui.group(|ui| {\n'
        f'            ui.heading("{_safe_text(card.get("title", "Card"))}");\n'
        f'            ui.label("{_safe_text(card.get("description", ""))}");\n'
        '        });'
        for card in cards
    )
    source = f'''use eframe::egui;

fn main() -> eframe::Result {{
    let native_options = eframe::NativeOptions::default();
    eframe::run_native(
        "{_safe_text(project["name"])}",
        native_options,
        Box::new(|_| Ok(Box::<DesignatioApp>::default())),
    )
}}

#[derive(Default)]
struct DesignatioApp;

impl eframe::App for DesignatioApp {{
    fn update(&mut self, ctx: &egui::Context, _frame: &mut eframe::Frame) {{
        egui::CentralPanel::default().show(ctx, |ui| {{
            ui.heading("{_safe_text(header.get("title", project["name"]))}");
            ui.label("{_safe_text(header.get("description", ""))}");
{card_views}
        }});
    }}
}}
'''
    (output / "main.rs").write_text(source, encoding="utf-8")
    (output / "Cargo.toml").write_text(
        '[package]\nname = "designatio-generated"\nversion = "0.1.0"\nedition = "2021"\n\n'
        '[dependencies]\neframe = "0.33"\n',
        encoding="utf-8",
    )
    return {"renderer": "egui", "entry": str((output / "main.rs").resolve()), "files": [str((output / "main.rs").resolve()), str((output / "Cargo.toml").resolve())]}


RENDERER_REGISTRY: dict[str, Callable[[dict[str, Any], str | Path], dict[str, Any]]] = {
    "flutter": render_flutter,
    "dart": render_flutter,
    "swiftui": render_swiftui,
    "swift": render_swiftui,
    "compose": render_compose,
    "compose-multiplatform": render_compose,
    "kotlin": render_compose,
    "egui": render_egui,
    "rust-egui": render_egui,
}


def render_native(project: dict[str, Any], target: str, output_dir: str | Path) -> dict[str, Any]:
    normalized = target.lower().strip()
    renderer = RENDERER_REGISTRY.get(normalized)
    if renderer is None:
        raise ValueError(f"Unsupported native renderer: {target}")
    result = renderer(project, output_dir)
    return result
